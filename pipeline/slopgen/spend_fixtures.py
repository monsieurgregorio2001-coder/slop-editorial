"""Parity fixtures for the site's spend cap toy.

    python -m slopgen.spend_fixtures            write ../site/test/fixtures/spend-parity.json
    python -m slopgen.spend_fixtures --check    exit 1 when the committed file differs from what this package computes

The fixtures hold every input and the exact output of slopgen.spend. The site's Node tests replay them
against the TypeScript port. Nothing here talks to a provider.
"""
import json
import sys
from pathlib import Path

from .spend import evaluate, planned_total, price_table

OUT = Path(__file__).resolve().parents[2] / "site" / "test" / "fixtures" / "spend-parity.json"
SIZES = [(1024, 1280), (1024, 1024)]
PLATES = [1, 2, 5, 9, 12, 20]
REROLLS = [0, 1, 3]
CAPS = [0, 0.25, 1, 5, 20]
ODD_CAPS = [-0.01, "nan", "inf"]


def cap_value(c):
    return float(c) if isinstance(c, str) else c


def build():
    rows = []
    for width, height in SIZES:
        for entry in price_table(width, height):
            for plates in PLATES:
                for rerolls in REROLLS:
                    jobs = plates * (1 + rerolls)
                    total = planned_total(entry["usd"], jobs)
                    caps = CAPS + (ODD_CAPS if plates in (1, 9) and rerolls == 1 else [])
                    for cap in caps:
                        verdict = evaluate(total, cap_value(cap), entry["provider"], entry["free"])
                        rows.append({"width": width, "height": height, "provider": entry["provider"], "model": entry["model"],
                                     "mode": entry["mode"], "free": entry["free"], "per_image": entry["usd"], "plates": plates,
                                     "rerolls": rerolls, "jobs": jobs, "cap": cap, "total": total, **verdict})
    return {"schema": 1, "note": "Generated by python -m slopgen.spend_fixtures. Do not edit by hand.", "rows": rows}


def render():
    data = build()
    rows = ",\n".join("  " + json.dumps(r, separators=(",", ":")) for r in data["rows"])
    return '{"schema":1,"note":' + json.dumps(data["note"]) + ',"rows":[\n' + rows + "\n]}\n"


def main(argv):
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} differs from what slopgen computes. Run: python -m slopgen.spend_fixtures")
            return 1
        print(f"{OUT}: {len(build()['rows'])} fixtures match")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT}: {len(build()['rows'])} fixtures")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
